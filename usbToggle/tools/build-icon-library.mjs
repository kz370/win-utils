// Builds ui/icon-library.js from tools/icon-library.txt and the lucide-static package.
// Usage: npm run icons:library
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const lucideDir = dirname(require.resolve("lucide-static/package.json"));
const version = JSON.parse(readFileSync(join(lucideDir, "package.json"), "utf8")).version;
const tags = JSON.parse(readFileSync(join(lucideDir, "tags.json"), "utf8"));
const license = readFileSync(join(lucideDir, "LICENSE"), "utf8").trim();

// Parse the pick list.
const groups = [];
const seen = new Set();
const missing = [];
for (const raw of readFileSync(join(root, "tools", "icon-library.txt"), "utf8").split(/\r?\n/)) {
  const line = raw.trim();
  if (!line) continue;
  if (line.startsWith("##")) {
    const m = line.slice(2).split("|").map((s) => s.trim());
    if (m.length !== 2) throw new Error(`Group lines look like "## Label | color": ${line}`);
    groups.push({ label: m[0], color: m[1], icons: [] });
    continue;
  }
  if (line.startsWith("#")) continue; // comment
  if (!groups.length) throw new Error("Icon names must come after a '## Label | color' line.");
  for (const name of line.split(/\s+/)) {
    if (seen.has(name)) continue;
    let svg;
    try {
      svg = readFileSync(join(lucideDir, "icons", `${name}.svg`), "utf8");
    } catch {
      missing.push(name);
      continue;
    }
    seen.add(name);
    const body = svg
      .match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1]
      .replace(/\s*\n\s*/g, " ")
      .trim()
      .replace(/" \/>/g, '"/>')
      .replace(/>\s+</g, "><");
    const keywords = (tags[name] || []).filter((t) => /^[\x20-\x7e]+$/.test(t)).join(" ").slice(0, 120);
    groups[groups.length - 1].icons.push({ name, body, keywords });
  }
}
if (missing.length) console.warn(`Not in Lucide ${version}, skipped: ${missing.join(", ")}`);

const q = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const lines = [
  "/*! Icon library for the device icon picker: a curated subset of Lucide",
  ` *  (https://lucide.dev) v${version}, generated by tools/build-icon-library.mjs from`,
  " *  tools/icon-library.txt. Do not edit by hand.",
  " *",
  ...license.split(/\r?\n/).map((l) => (l ? ` *  ${l}` : " *")),
  " */",
  "(function () {",
  '  // name -> [SVG body, search keywords]. Stored device icon names are "l-<name>".',
  "  const I = {",
  ...groups.flatMap((g) => g.icons.map((ic) => `    ${q(ic.name)}: [${q(ic.body)}, ${q(ic.keywords)}],`)),
  "  };",
  "  const GROUPS = [",
  ...groups.map((g) => `    [${q(g.label)}, ${q(g.color)}, ${JSON.stringify(g.icons.map((i) => i.name))}],`),
  "  ];",
  `
  const wrap = (body) =>
    \`<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${body}</svg>\`;

  const groups = GROUPS.map(([label, color, names]) => ({
    label,
    color,
    icons: names.map((name) => ({ key: "l-" + name, name, keywords: I[name][1] })),
  }));
  const colorByKey = {};
  for (const g of groups) for (const ic of g.icons) colorByKey[ic.key] = g.color;

  window.ICON_LIBRARY = {
    groups,
    count: Object.keys(I).length,
    has: (key) => typeof key === "string" && key.startsWith("l-") && key.slice(2) in I,
    svg: (key) => wrap(I[key.slice(2)][0]),
    color: (key) => colorByKey[key] || "other",
  };
})();`,
];
writeFileSync(join(root, "ui", "icon-library.js"), lines.join("\n") + "\n");
console.log(`ui/icon-library.js: ${seen.size} icons in ${groups.length} groups (Lucide ${version}).`);
